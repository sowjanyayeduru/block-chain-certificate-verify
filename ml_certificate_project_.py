import gradio as gr
import pytesseract
import cv2
import numpy as np
import pandas as pd
import joblib
from PIL import Image
from datetime import datetime

# Load trained model, scaler, and encoders
model = joblib.load("certificate_validation_model.pkl")
scaler = joblib.load("scaler.pkl")
label_encoders = joblib.load("label_encoders.pkl")

# OCR-based text extraction and classification
def process_certificate_image(image):
    # Convert image to OpenCV format
    img = np.array(image)
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    # Extract text using Tesseract OCR
    extracted_text = pytesseract.image_to_string(gray)

    # Simulated metadata extraction from text
    # In production, use regex or NLP to accurately extract each field
    issuer = next((line for line in extracted_text.split('\n') if "Ltd" in line or "Group" in line), "Unknown Issuer")
    recipient = next((line for line in extracted_text.split('\n') if "to" in line), "Unknown Recipient").split("to")[-1].strip()
    cert_type = "Academic" if "Academic" in extracted_text else "Training"
    date_line = next((line for line in extracted_text.split('\n') if "202" in line), "2022-01-01")
    blockchain_status = "Verified" if "verified" in extracted_text.lower() else "Pending"

    try:
        date_issued = datetime.strptime(date_line.strip(), "%Y-%m-%d")
    except:
        date_issued = datetime(2022, 1, 1)

    # Fill remaining data
    validity = 2  # default
    anomaly_score = 0.1  # simulated

    # Encode fields
    try:
        issuer_encoded = label_encoders["Issuer_Name"].transform([issuer])[0]
    except:
        issuer_encoded = 0
    try:
        recipient_encoded = label_encoders["Recipient_Name"].transform([recipient])[0]
    except:
        recipient_encoded = 0
    try:
        cert_type_encoded = label_encoders["Certificate_Type"].transform([cert_type])[0]
    except:
        cert_type_encoded = 0
    try:
        blockchain_encoded = label_encoders["Blockchain_Status"].transform([blockchain_status])[0]
    except:
        blockchain_encoded = 0

    # Date features
    days_since_issued = (datetime.now() - date_issued).days

    # Prepare input for prediction
    features = np.array([[issuer_encoded, recipient_encoded, cert_type_encoded, date_issued.timestamp(),
                          validity, anomaly_score, blockchain_encoded]])

    features_scaled = scaler.transform(features)
    prediction = model.predict(features_scaled)[0]

    result = "✅ This certificate is REAL (VALID)" if prediction == 1 else "❌ This certificate is FAKE or INVALID"

    return f"Prediction: {result}\n\nExtracted Info:\nIssuer: {issuer}\nRecipient: {recipient}\nDate: {date_issued.date()}\nCertificate Type: {cert_type}\nBlockchain Status: {blockchain_status}"

gr.Interface(
    fn=process_certificate_image,
    inputs=gr.Image(type="pil", label="Upload Certificate Image"),
    outputs="text",
    title="📜 AI + Blockchain Certificate Validator",
    description="Upload a scanned or digital certificate. The system will extract metadata using OCR and predict whether the certificate is valid or fake using trained AI."
).launch(share=True)

